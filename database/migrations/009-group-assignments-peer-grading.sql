BEGIN;

CREATE TABLE IF NOT EXISTS assignment_group_settings (
    assignment_id BIGINT PRIMARY KEY REFERENCES assignments(assignment_id),
    delivery_mode VARCHAR(20) NOT NULL CHECK (delivery_mode IN ('INDIVIDUAL','GROUP')),
    target_mode VARCHAR(20) NOT NULL DEFAULT 'ALL' CHECK (target_mode IN ('ALL','SELECTED')),
    teacher_weight NUMERIC(5,2) NOT NULL DEFAULT 70 CHECK (teacher_weight BETWEEN 0 AND 100),
    peer_weight NUMERIC(5,2) NOT NULL DEFAULT 30 CHECK (peer_weight BETWEEN 0 AND 100),
    revision BIGINT NOT NULL DEFAULT 0 CHECK (revision >= 0),
    CHECK (teacher_weight + peer_weight = 100)
);

CREATE TABLE IF NOT EXISTS assignment_group_targets (
    target_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES assignments(assignment_id),
    class_id BIGINT NOT NULL REFERENCES subject_classes(class_id),
    group_id BIGINT NOT NULL,
    group_name VARCHAR(100) NOT NULL CHECK (btrim(group_name) <> ''),
    owner_enrollment_id BIGINT REFERENCES class_enrollments(enrollment_id),
    frozen_at TIMESTAMPTZ,
    peer_closed_at TIMESTAMPTZ,
    FOREIGN KEY (group_id, class_id) REFERENCES project_groups(group_id, class_id),
    UNIQUE (assignment_id, group_id),
    UNIQUE (target_id, assignment_id),
    CHECK (frozen_at IS NULL OR owner_enrollment_id IS NOT NULL),
    CHECK (peer_closed_at IS NULL OR frozen_at IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS assignment_group_members (
    target_id BIGINT NOT NULL REFERENCES assignment_group_targets(target_id),
    student_id BIGINT NOT NULL REFERENCES users(user_id),
    enrollment_id BIGINT NOT NULL REFERENCES class_enrollments(enrollment_id),
    student_name VARCHAR(100) NOT NULL,
    PRIMARY KEY (target_id, student_id),
    UNIQUE (target_id, enrollment_id)
);

ALTER TABLE submissions ADD COLUMN IF NOT EXISTS assignment_group_target_id BIGINT;

DO $group_submission_constraints$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='submissions'::regclass
                   AND conname='fk_submission_assignment_group') THEN
        ALTER TABLE submissions ADD CONSTRAINT fk_submission_assignment_group
            FOREIGN KEY (assignment_group_target_id, assignment_id)
            REFERENCES assignment_group_targets(target_id, assignment_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='submissions'::regclass
                   AND conname='uq_group_submission_identity') THEN
        ALTER TABLE submissions ADD CONSTRAINT uq_group_submission_identity
            UNIQUE (submission_id, assignment_group_target_id);
    END IF;
END
$group_submission_constraints$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_group_one_in_progress
    ON submissions(assignment_group_target_id)
    WHERE assignment_group_target_id IS NOT NULL AND status='IN_PROGRESS';
CREATE UNIQUE INDEX IF NOT EXISTS uq_group_attempt_number
    ON submissions(assignment_group_target_id, attempt_number)
    WHERE assignment_group_target_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_assignment_group_member_student
    ON assignment_group_members(student_id, target_id);

CREATE TABLE IF NOT EXISTS assignment_peer_reviews (
    target_id BIGINT NOT NULL,
    rater_student_id BIGINT NOT NULL,
    reviewee_student_id BIGINT NOT NULL,
    score NUMERIC(10,2) NOT NULL CHECK (score BETWEEN 0 AND 100),
    feedback VARCHAR(2000) NOT NULL DEFAULT '',
    revision BIGINT NOT NULL DEFAULT 0 CHECK (revision >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (target_id, rater_student_id, reviewee_student_id),
    FOREIGN KEY (target_id, rater_student_id) REFERENCES assignment_group_members(target_id, student_id),
    FOREIGN KEY (target_id, reviewee_student_id) REFERENCES assignment_group_members(target_id, student_id),
    CHECK (rater_student_id <> reviewee_student_id)
);

CREATE TABLE IF NOT EXISTS assignment_group_results (
    target_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    submission_id BIGINT NOT NULL,
    teacher_score NUMERIC(10,2) NOT NULL CHECK (teacher_score BETWEEN 0 AND 100),
    peer_score NUMERIC(12,6) NOT NULL CHECK (peer_score BETWEEN 0 AND 100),
    final_score NUMERIC(10,2) NOT NULL CHECK (final_score BETWEEN 0 AND 100),
    teacher_weight NUMERIC(5,2) NOT NULL CHECK (teacher_weight BETWEEN 0 AND 100),
    peer_weight NUMERIC(5,2) NOT NULL CHECK (peer_weight BETWEEN 0 AND 100),
    received_reviews INTEGER NOT NULL CHECK (received_reviews >= 0),
    eligible_reviews INTEGER NOT NULL CHECK (eligible_reviews >= received_reviews),
    released_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (target_id, student_id),
    FOREIGN KEY (target_id, student_id) REFERENCES assignment_group_members(target_id, student_id),
    FOREIGN KEY (submission_id, target_id) REFERENCES submissions(submission_id, assignment_group_target_id),
    CHECK (teacher_weight + peer_weight = 100)
);

COMMIT;
