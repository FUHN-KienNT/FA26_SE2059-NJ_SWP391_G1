-- Additive implementation audit storage (not new conceptual business entities).
-- Existing rows start at migration time: earlier responsibility cannot be reconstructed.
CREATE TABLE IF NOT EXISTS responsibility_periods (
  period_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_type VARCHAR(30) NOT NULL,
  source_id BIGINT NOT NULL,
  responsibility_type VARCHAR(20) NOT NULL,
  user_id BIGINT NOT NULL REFERENCES users(user_id),
  subject_id BIGINT REFERENCES subjects(subject_id),
  class_id BIGINT REFERENCES subject_classes(class_id),
  started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ended_at TIMESTAMPTZ,
  CHECK (ended_at IS NULL OR ended_at >= started_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_responsibility_open
  ON responsibility_periods(source_type,source_id) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_responsibility_deadline
  ON responsibility_periods(responsibility_type,subject_id,class_id,started_at,ended_at);
CREATE TABLE IF NOT EXISTS responsibility_deadline_breaches (
  breach_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  breach_type VARCHAR(20) NOT NULL CHECK (breach_type IN ('ESSAY','REQUEST')),
  item_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL REFERENCES users(user_id),
  term_id BIGINT NOT NULL REFERENCES academic_terms(term_id),
  deadline_at TIMESTAMPTZ NOT NULL,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (breach_type,item_id,user_id)
);

CREATE OR REPLACE FUNCTION ams_record_responsibility() RETURNS TRIGGER AS $$
DECLARE
  source_key BIGINT; owner_key BIGINT; subject_key BIGINT; class_key BIGINT;
  kind VARCHAR(20); enabled BOOLEAN;
BEGIN
  IF TG_TABLE_NAME = 'subject_classes' THEN
    IF TG_OP = 'UPDATE' AND NEW.teacher_id IS NOT DISTINCT FROM OLD.teacher_id THEN RETURN NEW; END IF;
    source_key := NEW.class_id; owner_key := NEW.teacher_id; class_key := NEW.class_id;
    SELECT subject_id INTO subject_key FROM subject_terms WHERE subject_term_id=NEW.subject_term_id;
    kind := 'TEACHER'; enabled := owner_key IS NOT NULL;
  ELSIF TG_TABLE_NAME = 'subject_experts' THEN
    IF TG_OP = 'UPDATE' AND NEW.is_active = OLD.is_active AND NEW.responsibility_type = OLD.responsibility_type
      AND NEW.expert_id = OLD.expert_id AND NEW.subject_id = OLD.subject_id THEN RETURN NEW; END IF;
    source_key := NEW.subject_expert_id; owner_key := NEW.expert_id; subject_key := NEW.subject_id;
    kind := NEW.responsibility_type; enabled := NEW.is_active;
  ELSIF TG_TABLE_NAME = 'class_experts' THEN
    IF TG_OP = 'UPDATE' AND NEW.is_active = OLD.is_active AND NEW.expert_id = OLD.expert_id
      AND NEW.class_id = OLD.class_id AND NEW.subject_id = OLD.subject_id THEN RETURN NEW; END IF;
    source_key := NEW.class_expert_id; owner_key := NEW.expert_id; subject_key := NEW.subject_id; class_key := NEW.class_id;
    kind := 'CLASS_EXPERT'; enabled := NEW.is_active;
  ELSE
    IF TG_OP = 'UPDATE' AND NEW.is_active = OLD.is_active AND NEW.teacher_id = OLD.teacher_id
      AND NEW.subject_id = OLD.subject_id THEN RETURN NEW; END IF;
    source_key := NEW.teacher_subject_id; owner_key := NEW.teacher_id; subject_key := NEW.subject_id;
    kind := 'ELIGIBILITY'; enabled := NEW.is_active;
  END IF;
  UPDATE responsibility_periods SET ended_at=CURRENT_TIMESTAMP
    WHERE source_type=TG_TABLE_NAME AND source_id=source_key AND ended_at IS NULL;
  IF enabled THEN
    INSERT INTO responsibility_periods(source_type,source_id,responsibility_type,user_id,subject_id,class_id)
      VALUES(TG_TABLE_NAME,source_key,kind,owner_key,subject_key,class_key);
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

