-- AMS database design V2 - PostgreSQL
-- Source: ams-database-design.puml (18 tables).
-- Run on an EMPTY database: psql -v ON_ERROR_STOP=1 -d ams -f schemaV2.sql
-- This is a fresh schema, not a migration from schema.sql. No data is dropped.
-- Entity names use the project's plural snake_case convention; User -> user_accounts.
-- All timestamps represent instants (TIMESTAMPTZ). Display local time in the UI.
-- REVIEW_REQUIRED is derived, not an account_status value.
-- System Setting, Answer Option, Student Answer and Overflow Batch Item are not
-- separate tables in this design. Embedded collections use JSONB arrays.
--
-- Transactional service responsibilities (not enforced by FK/CHECK alone):
--   * Validate actor role, active account, Subject responsibility and permissions.
--   * Maintain 1-2 Primary and 0-2 Supporting Subject Experts, and 1-2 active
--     Class Experts; their Subject must match the Class's Subject Term.
--   * Match Teacher eligibility to the Class Subject, and Registration to Class
--     Subject Term. Preserve historical assignments and referenced academic data.
--   * Serialize Class capacity changes, enrollments and invitation reservations
--     by locking the Class row. Count ACTIVE enrollments plus unexpired PENDING
--     invitations. Recheck placement eligibility and one active registration.
--   * Expire invitations/offers via a job AND before relevant writes. The partial
--     unique indexes use status, not wall-clock time; elapsed rows must transition
--     to EXPIRED before replacement. Never use now() in a partial index predicate.
--   * On invitation acceptance, verify Google email and create/reuse account,
--     registration and enrollment atomically, converting the reserved seat once.
--   * Review requests and accept offers with row locks/conditional updates so the
--     first successful decision wins. Finalize at most one Class per request.
--   * Check JSON item shape, unique embedded IDs, answer/question ownership,
--     option correctness, score totals, attempt limits and publication rules.
--   * Preserve published question/options snapshots; enforce submit/grading/release
--     deadlines, Student ownership and immutability in authorized transactions.
-- These checks belong in the service layer, consistent with the current project.

BEGIN;

-- 01. User
CREATE TABLE user_accounts (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL CHECK (btrim(full_name) <> ''),
    email VARCHAR(254) NOT NULL CHECK (btrim(email) <> ''),
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'EXPERT', 'TEACHER', 'STUDENT')),
    account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (account_status IN ('ACTIVE', 'INACTIVE')),
    password_hash VARCHAR(255),
    google_subject VARCHAR(255) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ,
    CONSTRAINT ck_user_credentials CHECK (
        (role = 'STUDENT' AND password_hash IS NULL
            AND google_subject IS NOT NULL AND btrim(google_subject) <> '')
        OR
        (role <> 'STUDENT' AND password_hash IS NOT NULL
            AND btrim(password_hash) <> '' AND google_subject IS NULL)
    ),
    CONSTRAINT ck_user_last_login CHECK (last_login_at IS NULL OR last_login_at >= created_at)
);
CREATE UNIQUE INDEX uq_user_email_normalized ON user_accounts (lower(btrim(email)));

-- 02. Subject
CREATE TABLE subjects (
    subject_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_code VARCHAR(30) NOT NULL UNIQUE CHECK (btrim(subject_code) <> ''),
    subject_name VARCHAR(150) NOT NULL CHECK (btrim(subject_name) <> ''),
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- 03. Academic Term
CREATE TABLE academic_terms (
    term_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_code VARCHAR(30) NOT NULL UNIQUE CHECK (btrim(term_code) <> ''),
    term_name VARCHAR(100) NOT NULL CHECK (btrim(term_name) <> ''),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_term_dates CHECK (ends_at > starts_at),
    CONSTRAINT ck_current_term_active CHECK (NOT is_current OR is_active)
);
CREATE UNIQUE INDEX uq_one_current_term ON academic_terms (is_current) WHERE is_current;

-- 04. Subject Term
CREATE TABLE subject_terms (
    subject_term_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subjects (subject_id),
    term_id BIGINT NOT NULL REFERENCES academic_terms (term_id),
    registration_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    registration_opens_at TIMESTAMPTZ NOT NULL,
    registration_closes_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_subject_term UNIQUE (subject_id, term_id),
    CONSTRAINT ck_registration_window CHECK (registration_closes_at > registration_opens_at)
);
CREATE INDEX ix_subject_terms_term ON subject_terms (term_id);

-- 05. Subject Expert - the pair is reused on reactivation.
CREATE TABLE subject_experts (
    subject_id BIGINT NOT NULL REFERENCES subjects (subject_id),
    expert_id BIGINT NOT NULL REFERENCES user_accounts (user_id),
    responsibility_type VARCHAR(20) NOT NULL
        CHECK (responsibility_type IN ('PRIMARY', 'SUPPORTING')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (subject_id, expert_id)
);
CREATE INDEX ix_subject_experts_expert ON subject_experts (expert_id);

-- 06. Teacher Subject Eligibility
CREATE TABLE teacher_subject_eligibilities (
    teacher_id BIGINT NOT NULL REFERENCES user_accounts (user_id),
    subject_id BIGINT NOT NULL REFERENCES subjects (subject_id),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deactivated_at TIMESTAMPTZ,
    PRIMARY KEY (teacher_id, subject_id),
    CONSTRAINT ck_eligibility_state CHECK (is_active = (deactivated_at IS NULL)),
    CONSTRAINT ck_eligibility_dates CHECK (deactivated_at IS NULL OR deactivated_at >= assigned_at)
);
CREATE INDEX ix_teacher_eligibilities_subject ON teacher_subject_eligibilities (subject_id);

-- 07. Subject Class - teacher_id may be NULL during setup.
CREATE TABLE subject_classes (
    class_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_term_id BIGINT NOT NULL REFERENCES subject_terms (subject_term_id),
    teacher_id BIGINT REFERENCES user_accounts (user_id),
    class_code VARCHAR(30) NOT NULL UNIQUE CHECK (btrim(class_code) <> ''),
    class_name VARCHAR(150) NOT NULL CHECK (btrim(class_name) <> ''),
    capacity INTEGER NOT NULL CHECK (capacity BETWEEN 10 AND 40),
    registration_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE INDEX ix_classes_subject_term ON subject_classes (subject_term_id);
CREATE INDEX ix_classes_teacher ON subject_classes (teacher_id);

-- 08. Class Expert - composite FK requires existing Subject Expert membership.
-- Application additionally checks active membership and matching Class Subject.
CREATE TABLE class_experts (
    class_id BIGINT NOT NULL REFERENCES subject_classes (class_id),
    expert_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deactivated_at TIMESTAMPTZ,
    PRIMARY KEY (class_id, expert_id),
    CONSTRAINT fk_class_expert_subject_expert FOREIGN KEY (subject_id, expert_id)
        REFERENCES subject_experts (subject_id, expert_id),
    CONSTRAINT ck_class_expert_state CHECK (is_active = (deactivated_at IS NULL)),
    CONSTRAINT ck_class_expert_dates CHECK (deactivated_at IS NULL OR deactivated_at >= assigned_at)
);
CREATE INDEX ix_class_experts_subject_expert ON class_experts (subject_id, expert_id);
CREATE INDEX ix_class_experts_expert ON class_experts (expert_id);

-- 09. Subject Registration
CREATE TABLE subject_registrations (
    registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES user_accounts (user_id),
    subject_term_id BIGINT NOT NULL REFERENCES subject_terms (subject_term_id),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    registered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deactivated_at TIMESTAMPTZ,
    CONSTRAINT uq_student_subject_term UNIQUE (student_id, subject_term_id),
    CONSTRAINT ck_registration_state CHECK ((status = 'ACTIVE') = (deactivated_at IS NULL)),
    CONSTRAINT ck_registration_dates CHECK (deactivated_at IS NULL OR deactivated_at >= registered_at)
);
CREATE INDEX ix_registrations_subject_term ON subject_registrations (subject_term_id);

-- 10. Class Enrollment - multiple historical episodes, one active placement.
CREATE TABLE class_enrollments (
    enrollment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id BIGINT NOT NULL REFERENCES subject_registrations (registration_id),
    class_id BIGINT NOT NULL REFERENCES subject_classes (class_id),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    enrollment_method VARCHAR(20) NOT NULL
        CHECK (enrollment_method IN ('AUTO', 'MANUAL', 'IMPORT', 'INVITATION', 'CLASS_CHANGE')),
    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deactivated_at TIMESTAMPTZ,
    CONSTRAINT ck_enrollment_state CHECK ((status = 'ACTIVE') = (deactivated_at IS NULL)),
    CONSTRAINT ck_enrollment_dates CHECK (deactivated_at IS NULL OR deactivated_at >= enrolled_at)
);
CREATE UNIQUE INDEX uq_one_active_enrollment_per_registration
    ON class_enrollments (registration_id) WHERE status = 'ACTIVE';
CREATE INDEX ix_enrollments_registration ON class_enrollments (registration_id);
CREATE INDEX ix_enrollments_class_status ON class_enrollments (class_id, status);

-- 11. Student Invitation - no User is required until accepted.
CREATE TABLE student_invitations (
    invitation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL REFERENCES subject_classes (class_id),
    invited_by BIGINT NOT NULL REFERENCES user_accounts (user_id),
    email VARCHAR(254) NOT NULL CHECK (btrim(email) <> ''),
    full_name VARCHAR(150) NOT NULL CHECK (btrim(full_name) <> ''),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'ACCEPTED', 'EXPIRED', 'CANCELLED')),
    sent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '48 hours'),
    accepted_at TIMESTAMPTZ,
    accepted_by BIGINT REFERENCES user_accounts (user_id),
    enrollment_id BIGINT REFERENCES class_enrollments (enrollment_id),
    CONSTRAINT ck_invitation_expiry CHECK (expires_at = sent_at + INTERVAL '48 hours'),
    CONSTRAINT ck_invitation_acceptance CHECK (
        (status = 'ACCEPTED' AND accepted_at IS NOT NULL AND accepted_by IS NOT NULL
            AND enrollment_id IS NOT NULL AND accepted_at >= sent_at AND accepted_at < expires_at)
        OR (status <> 'ACCEPTED' AND accepted_at IS NULL AND accepted_by IS NULL AND enrollment_id IS NULL)
    )
);
CREATE UNIQUE INDEX uq_pending_invitation_class_email
    ON student_invitations (class_id, lower(btrim(email))) WHERE status = 'PENDING';
CREATE INDEX ix_invitations_pending_expiry ON student_invitations (expires_at) WHERE status = 'PENDING';
CREATE INDEX ix_invitations_class ON student_invitations (class_id);
CREATE INDEX ix_invitations_inviter ON student_invitations (invited_by);
CREATE INDEX ix_invitations_accepted_by ON student_invitations (accepted_by);
CREATE INDEX ix_invitations_enrollment ON student_invitations (enrollment_id);

-- 12. Overflow Batch
-- overflow_students: [{email, full_name, status, ...processing metadata}].
-- No User FK is required for an embedded entry whose account does not yet exist.
CREATE TABLE overflow_batches (
    overflow_batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_class_id BIGINT NOT NULL REFERENCES subject_classes (class_id),
    imported_by BIGINT NOT NULL REFERENCES user_accounts (user_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'PROCESSING', 'COMPLETED')),
    overflow_students JSONB NOT NULL DEFAULT '[]'::jsonb
        CHECK (jsonb_typeof(overflow_students) = 'array')
);
CREATE INDEX ix_overflow_batches_class ON overflow_batches (source_class_id);
CREATE INDEX ix_overflow_batches_importer ON overflow_batches (imported_by);

-- 13. Additional Class Request - multiple historical requests per batch.
CREATE TABLE additional_class_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    overflow_batch_id BIGINT NOT NULL REFERENCES overflow_batches (overflow_batch_id),
    requested_by BIGINT NOT NULL REFERENCES user_accounts (user_id),
    preferred_teacher_id BIGINT REFERENCES user_accounts (user_id),
    willing_to_teach BOOLEAN NOT NULL DEFAULT FALSE,
    overflow_context TEXT NOT NULL CHECK (btrim(overflow_context) <> ''),
    note TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING_REVIEW'
        CHECK (status IN ('PENDING_REVIEW', 'APPROVED', 'RESOLVED', 'REJECTED')),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    review_due_at TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '48 hours'),
    reviewed_by BIGINT REFERENCES user_accounts (user_id),
    reviewed_at TIMESTAMPTZ,
    decision_reason TEXT,
    created_class_id BIGINT UNIQUE REFERENCES subject_classes (class_id),
    resolved_at TIMESTAMPTZ,
    CONSTRAINT ck_request_review_due CHECK (review_due_at = requested_at + INTERVAL '48 hours'),
    CONSTRAINT ck_request_review_pair CHECK ((reviewed_by IS NULL) = (reviewed_at IS NULL)),
    CONSTRAINT ck_request_review_date CHECK (reviewed_at IS NULL OR reviewed_at >= requested_at),
    CONSTRAINT ck_request_review_required CHECK (status = 'PENDING_REVIEW' OR reviewed_at IS NOT NULL),
    CONSTRAINT ck_request_rejection_reason CHECK (
        status <> 'REJECTED' OR (decision_reason IS NOT NULL AND btrim(decision_reason) <> '')
    ),
    CONSTRAINT ck_request_resolution CHECK (
        (status = 'RESOLVED' AND created_class_id IS NOT NULL AND resolved_at IS NOT NULL
            AND reviewed_at IS NOT NULL AND resolved_at >= reviewed_at)
        OR (status <> 'RESOLVED' AND resolved_at IS NULL)
    )
);
CREATE UNIQUE INDEX uq_one_active_request_per_batch
    ON additional_class_requests (overflow_batch_id) WHERE status IN ('PENDING_REVIEW', 'APPROVED');
CREATE INDEX ix_requests_batch ON additional_class_requests (overflow_batch_id);
CREATE INDEX ix_requests_requester ON additional_class_requests (requested_by);
CREATE INDEX ix_requests_preferred_teacher ON additional_class_requests (preferred_teacher_id);
CREATE INDEX ix_requests_reviewer ON additional_class_requests (reviewed_by);
CREATE INDEX ix_requests_review_due ON additional_class_requests (review_due_at) WHERE status = 'PENDING_REVIEW';

-- 14. Additional Class Assignment Offer
CREATE TABLE additional_class_assignment_offers (
    offer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES additional_class_requests (request_id),
    teacher_id BIGINT NOT NULL REFERENCES user_accounts (user_id),
    offered_by BIGINT NOT NULL REFERENCES user_accounts (user_id),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'EXPIRED', 'CANCELLED')),
    sent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '48 hours'),
    responded_at TIMESTAMPTZ,
    response_note TEXT,
    CONSTRAINT ck_offer_expiry CHECK (expires_at = sent_at + INTERVAL '48 hours'),
    CONSTRAINT ck_offer_response CHECK (
        (status IN ('ACCEPTED', 'DECLINED') AND responded_at IS NOT NULL
            AND responded_at >= sent_at AND responded_at < expires_at)
        OR (status IN ('PENDING', 'EXPIRED', 'CANCELLED') AND responded_at IS NULL)
    )
);
CREATE UNIQUE INDEX uq_one_pending_offer_per_request
    ON additional_class_assignment_offers (request_id) WHERE status = 'PENDING';
CREATE UNIQUE INDEX uq_one_accepted_offer_per_request
    ON additional_class_assignment_offers (request_id) WHERE status = 'ACCEPTED';
CREATE INDEX ix_offers_request ON additional_class_assignment_offers (request_id);
CREATE INDEX ix_offers_teacher_status ON additional_class_assignment_offers (teacher_id, status);
CREATE INDEX ix_offers_sender ON additional_class_assignment_offers (offered_by);
CREATE INDEX ix_offers_pending_expiry ON additional_class_assignment_offers (expires_at) WHERE status = 'PENDING';

-- 15. Assignment Template
CREATE TABLE assignment_templates (
    template_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subjects (subject_id),
    title VARCHAR(200) NOT NULL CHECK (btrim(title) <> ''),
    instructions TEXT NOT NULL,
    maximum_score NUMERIC(10,2) NOT NULL CHECK (maximum_score > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_templates_subject ON assignment_templates (subject_id);

-- 16. Assignment - copy Template content on creation; keep its snapshot thereafter.
CREATE TABLE assignments (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL REFERENCES subject_classes (class_id),
    template_id BIGINT NOT NULL REFERENCES assignment_templates (template_id),
    title VARCHAR(200) NOT NULL CHECK (btrim(title) <> ''),
    assignment_purpose VARCHAR(20) NOT NULL CHECK (assignment_purpose IN ('REGULAR', 'PRACTICE')),
    response_type VARCHAR(20) NOT NULL CHECK (response_type IN ('ESSAY', 'OBJECTIVE')),
    instructions TEXT NOT NULL,
    scope_text TEXT,
    task_checklist JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(task_checklist) = 'array'),
    maximum_score NUMERIC(10,2) NOT NULL CHECK (maximum_score > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED', 'CANCELLED')),
    available_from TIMESTAMPTZ,
    due_at TIMESTAMPTZ,
    time_limit_minutes INTEGER CHECK (time_limit_minutes > 0),
    attempt_limit INTEGER,
    published_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    CONSTRAINT ck_assignment_combination CHECK (assignment_purpose <> 'PRACTICE' OR response_type = 'OBJECTIVE'),
    CONSTRAINT ck_assignment_attempt_limit CHECK (
        (assignment_purpose = 'PRACTICE' AND attempt_limit IS NOT NULL AND attempt_limit > 0)
        OR (assignment_purpose = 'REGULAR' AND attempt_limit IS NULL)
    ),
    CONSTRAINT ck_assignment_window CHECK (available_from IS NULL OR due_at IS NULL OR due_at > available_from),
    CONSTRAINT ck_assignment_publication CHECK (
        status <> 'PUBLISHED' OR (published_at IS NOT NULL AND available_from IS NOT NULL AND due_at IS NOT NULL)
    ),
    CONSTRAINT ck_assignment_draft_dates CHECK (status <> 'DRAFT' OR (published_at IS NULL AND cancelled_at IS NULL)),
    CONSTRAINT ck_assignment_cancellation CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL)),
    CONSTRAINT ck_assignment_cancel_date CHECK (published_at IS NULL OR cancelled_at IS NULL OR cancelled_at >= published_at)
);
CREATE INDEX ix_assignments_class ON assignments (class_id);
CREATE INDEX ix_assignments_template ON assignments (template_id);

-- 17. Question - options: [{option_id, option_order, option_text, is_correct}].
-- Option identifiers are embedded JSON keys, not FKs to a separate table.
CREATE TABLE questions (
    question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES assignments (assignment_id),
    question_order INTEGER NOT NULL CHECK (question_order > 0),
    question_text TEXT NOT NULL CHECK (btrim(question_text) <> ''),
    maximum_points NUMERIC(10,2) NOT NULL CHECK (maximum_points > 0),
    options JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(options) = 'array'),
    CONSTRAINT uq_question_order UNIQUE (assignment_id, question_order)
);

-- 18. Submission
-- answer: [{question_id, selected_option_id, awarded_points, updated_at}].
-- Validate embedded references against this Submission's Assignment in the service.
CREATE TABLE submissions (
    submission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES assignments (assignment_id),
    enrollment_id BIGINT NOT NULL REFERENCES class_enrollments (enrollment_id),
    graded_by BIGINT REFERENCES user_accounts (user_id),
    attempt_number INTEGER NOT NULL DEFAULT 1 CHECK (attempt_number > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS'
        CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'GRADED', 'RELEASED', 'EXPIRED', 'VOID')),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deadline_at TIMESTAMPTZ NOT NULL,
    submitted_at TIMESTAMPTZ,
    content TEXT,
    submission_link TEXT,
    score NUMERIC(10,2) CHECK (score >= 0),
    feedback TEXT,
    graded_at TIMESTAMPTZ,
    released_at TIMESTAMPTZ,
    answer JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(answer) = 'array'),
    CONSTRAINT uq_submission_attempt UNIQUE (assignment_id, enrollment_id, attempt_number),
    CONSTRAINT ck_submission_deadline CHECK (deadline_at > started_at),
    CONSTRAINT ck_submission_time CHECK (submitted_at IS NULL OR (submitted_at >= started_at AND submitted_at <= deadline_at)),
    CONSTRAINT ck_submission_grade_time CHECK (graded_at IS NULL OR (submitted_at IS NOT NULL AND graded_at >= submitted_at)),
    CONSTRAINT ck_submission_release_time CHECK (released_at IS NULL OR (graded_at IS NOT NULL AND released_at >= graded_at)),
    CONSTRAINT ck_submission_finalized CHECK (status NOT IN ('SUBMITTED', 'GRADED', 'RELEASED') OR submitted_at IS NOT NULL),
    CONSTRAINT ck_submission_graded CHECK (status NOT IN ('GRADED', 'RELEASED') OR (score IS NOT NULL AND graded_at IS NOT NULL)),
    CONSTRAINT ck_submission_released CHECK ((status = 'RELEASED') = (released_at IS NOT NULL)),
    CONSTRAINT ck_submission_unfinished CHECK (
        status NOT IN ('IN_PROGRESS', 'EXPIRED', 'VOID')
        OR (submitted_at IS NULL AND score IS NULL AND graded_at IS NULL AND released_at IS NULL)
    )
);
CREATE UNIQUE INDEX uq_one_in_progress_attempt
    ON submissions (assignment_id, enrollment_id) WHERE status = 'IN_PROGRESS';
CREATE INDEX ix_submissions_enrollment ON submissions (enrollment_id);
CREATE INDEX ix_submissions_grader ON submissions (graded_by);
CREATE INDEX ix_submissions_assignment_status ON submissions (assignment_id, status);

COMMIT;
