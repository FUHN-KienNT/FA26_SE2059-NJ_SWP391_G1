-- AMS PostgreSQL baseline synchronized with the current domain model.
-- Intended for a fresh database. Store and compare all TIMESTAMPTZ values in UTC.

CREATE TABLE users (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(50) NOT NULL CHECK (btrim(full_name) <> ''),
  email VARCHAR(100) NOT NULL CHECK (btrim(email) <> ''),
  role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','EXPERT','TEACHER','STUDENT')),
  account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (account_status IN ('ACTIVE','INACTIVE')),
  google_subject VARCHAR(255),
  password_hash VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK ((role = 'STUDENT' AND password_hash IS NULL) OR (role <> 'STUDENT' AND password_hash IS NOT NULL))
);
CREATE UNIQUE INDEX uq_users_email_normalized ON users (lower(btrim(email)));
CREATE UNIQUE INDEX uq_users_google_subject ON users (google_subject) WHERE google_subject IS NOT NULL;

CREATE TABLE academic_terms (
  term_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  term_code VARCHAR(20) NOT NULL UNIQUE CHECK (btrim(term_code) <> ''),
  term_name VARCHAR(100) NOT NULL CHECK (btrim(term_name) <> ''),
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  is_current BOOLEAN NOT NULL DEFAULT FALSE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  CHECK (ends_at > starts_at),
  CHECK (NOT is_current OR is_active)
);
CREATE UNIQUE INDEX uq_academic_terms_current ON academic_terms (is_current) WHERE is_current;

CREATE TABLE subjects (
  subject_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_code VARCHAR(30) NOT NULL UNIQUE CHECK (btrim(subject_code) <> ''),
  subject_name VARCHAR(150) NOT NULL CHECK (btrim(subject_name) <> ''),
  description TEXT,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE subject_experts (
  subject_expert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id BIGINT NOT NULL REFERENCES subjects(subject_id),
  expert_id BIGINT NOT NULL REFERENCES users(user_id),
  responsibility_type VARCHAR(20) NOT NULL CHECK (responsibility_type IN ('PRIMARY','SUPPORTING')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deactivated_at TIMESTAMPTZ,
  UNIQUE (subject_id, expert_id),
  CHECK (deactivated_at IS NULL OR deactivated_at >= assigned_at),
  CHECK ((is_active AND deactivated_at IS NULL) OR (NOT is_active AND deactivated_at IS NOT NULL))
);

CREATE TABLE teacher_subjects (
  teacher_subject_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id BIGINT NOT NULL REFERENCES users(user_id),
  subject_id BIGINT NOT NULL REFERENCES subjects(subject_id),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deactivated_at TIMESTAMPTZ,
  UNIQUE (teacher_id, subject_id),
  CHECK (deactivated_at IS NULL OR deactivated_at >= assigned_at),
  CHECK ((is_active AND deactivated_at IS NULL) OR (NOT is_active AND deactivated_at IS NOT NULL))
);

CREATE TABLE subject_terms (
  subject_term_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id BIGINT NOT NULL REFERENCES subjects(subject_id),
  term_id BIGINT NOT NULL REFERENCES academic_terms(term_id),
  registration_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  registration_opens_at TIMESTAMPTZ NOT NULL,
  registration_closes_at TIMESTAMPTZ NOT NULL,
  UNIQUE (subject_id, term_id),
  CHECK (registration_closes_at > registration_opens_at)
);

CREATE TABLE subject_classes (
  class_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_term_id BIGINT NOT NULL REFERENCES subject_terms(subject_term_id),
  teacher_id BIGINT REFERENCES users(user_id),
  class_code VARCHAR(30) NOT NULL UNIQUE CHECK (btrim(class_code) <> ''),
  class_name VARCHAR(150) NOT NULL CHECK (btrim(class_name) <> ''),
  capacity INTEGER NOT NULL CHECK (capacity BETWEEN 10 AND 40),
  registration_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE class_experts (
  class_expert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id BIGINT NOT NULL REFERENCES subject_classes(class_id),
  subject_id BIGINT NOT NULL REFERENCES subjects(subject_id),
  expert_id BIGINT NOT NULL REFERENCES users(user_id),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deactivated_at TIMESTAMPTZ,
  UNIQUE (class_id, expert_id),
  FOREIGN KEY (subject_id, expert_id) REFERENCES subject_experts(subject_id, expert_id),
  CHECK (deactivated_at IS NULL OR deactivated_at >= assigned_at),
  CHECK ((is_active AND deactivated_at IS NULL) OR (NOT is_active AND deactivated_at IS NOT NULL))
);

CREATE TABLE subject_registrations (
  registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL REFERENCES users(user_id),
  subject_term_id BIGINT NOT NULL REFERENCES subject_terms(subject_term_id),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
  registered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deactivated_at TIMESTAMPTZ,
  UNIQUE (student_id, subject_term_id),
  CHECK (deactivated_at IS NULL OR deactivated_at >= registered_at),
  CHECK ((status = 'ACTIVE' AND deactivated_at IS NULL) OR (status = 'INACTIVE' AND deactivated_at IS NOT NULL))
);

CREATE TABLE class_enrollments (
  enrollment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration_id BIGINT NOT NULL REFERENCES subject_registrations(registration_id),
  class_id BIGINT NOT NULL REFERENCES subject_classes(class_id),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
  enrollment_method VARCHAR(30) NOT NULL CHECK (enrollment_method IN ('SELF_REGISTRATION','MANUAL','IMPORT','INVITATION','CLASS_CHANGE')),
  enrolled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deactivated_at TIMESTAMPTZ,
  CHECK (deactivated_at IS NULL OR deactivated_at >= enrolled_at),
  CHECK ((status = 'ACTIVE' AND deactivated_at IS NULL) OR (status = 'INACTIVE' AND deactivated_at IS NOT NULL))
);
CREATE UNIQUE INDEX uq_class_enrollments_active_registration ON class_enrollments (registration_id) WHERE status = 'ACTIVE';

CREATE TABLE student_invitations (
  invitation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id BIGINT NOT NULL REFERENCES subject_classes(class_id),
  invited_by BIGINT NOT NULL REFERENCES users(user_id),
  email VARCHAR(254) NOT NULL CHECK (btrim(email) <> ''),
  full_name VARCHAR(150),
  token VARCHAR(255) NOT NULL UNIQUE,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','ACCEPTED','EXPIRED','CANCELLED')),
  sent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ NOT NULL,
  accepted_at TIMESTAMPTZ,
  accepted_by BIGINT REFERENCES users(user_id),
  enrollment_id BIGINT UNIQUE REFERENCES class_enrollments(enrollment_id),
  CHECK (expires_at = sent_at + INTERVAL '48 hours'),
  CHECK ((status = 'ACCEPTED' AND accepted_at IS NOT NULL AND accepted_by IS NOT NULL AND enrollment_id IS NOT NULL)
      OR (status <> 'ACCEPTED' AND accepted_at IS NULL AND accepted_by IS NULL AND enrollment_id IS NULL))
);

CREATE TABLE overflow_batches (
  overflow_batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_class_id BIGINT NOT NULL REFERENCES subject_classes(class_id),
  imported_by BIGINT NOT NULL REFERENCES users(user_id),
  source_file_name VARCHAR(255) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','PROCESSING','COMPLETED')),
  overflow_students JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(overflow_students) = 'array'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE additional_class_requests (
  request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  overflow_batch_id BIGINT NOT NULL REFERENCES overflow_batches(overflow_batch_id),
  requested_by BIGINT NOT NULL REFERENCES users(user_id),
  preferred_teacher_id BIGINT REFERENCES users(user_id),
  willing_to_teach BOOLEAN NOT NULL DEFAULT FALSE,
  overflow_context TEXT NOT NULL CHECK (btrim(overflow_context) <> ''),
  note TEXT,
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING_REVIEW' CHECK (status IN ('PENDING_REVIEW','APPROVED','REJECTED','RESOLVED')),
  requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  review_due_at TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '48 hours'),
  reviewed_by BIGINT REFERENCES users(user_id),
  reviewed_at TIMESTAMPTZ,
  decision_reason TEXT,
  created_class_id BIGINT UNIQUE REFERENCES subject_classes(class_id),
  resolved_at TIMESTAMPTZ,
  CHECK (review_due_at = requested_at + INTERVAL '48 hours'),
  CHECK ((status = 'PENDING_REVIEW' AND reviewed_by IS NULL AND reviewed_at IS NULL)
      OR (status <> 'PENDING_REVIEW' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
  CHECK (status <> 'REJECTED' OR (decision_reason IS NOT NULL AND btrim(decision_reason) <> '')),
  CHECK ((status = 'RESOLVED' AND created_class_id IS NOT NULL AND resolved_at IS NOT NULL)
      OR (status <> 'RESOLVED' AND resolved_at IS NULL))
);
CREATE UNIQUE INDEX uq_additional_class_requests_unresolved
  ON additional_class_requests (overflow_batch_id)
  WHERE status IN ('PENDING_REVIEW','APPROVED');

CREATE TABLE additional_class_assignment_offers (
  offer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES additional_class_requests(request_id),
  teacher_id BIGINT NOT NULL REFERENCES users(user_id),
  offered_by BIGINT NOT NULL REFERENCES users(user_id),
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','ACCEPTED','DECLINED','EXPIRED','CANCELLED')),
  sent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ NOT NULL,
  responded_at TIMESTAMPTZ,
  response_note TEXT,
  CHECK (expires_at = sent_at + INTERVAL '48 hours'),
  CHECK ((status IN ('ACCEPTED','DECLINED') AND responded_at IS NOT NULL)
      OR (status NOT IN ('ACCEPTED','DECLINED') AND responded_at IS NULL))
);
CREATE UNIQUE INDEX uq_additional_class_assignment_offers_pending
  ON additional_class_assignment_offers (request_id)
  WHERE status = 'PENDING';

CREATE TABLE assignment_templates (
  template_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id BIGINT NOT NULL REFERENCES subjects(subject_id),
  title VARCHAR(200) NOT NULL CHECK (btrim(title) <> ''),
  instructions TEXT NOT NULL,
  maximum_score NUMERIC(10,2) NOT NULL CHECK (maximum_score > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE assignments (
  assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id BIGINT NOT NULL REFERENCES subject_classes(class_id),
  template_id BIGINT NOT NULL REFERENCES assignment_templates(template_id),
  title VARCHAR(200) NOT NULL CHECK (btrim(title) <> ''),
  assignment_purpose VARCHAR(20) NOT NULL CHECK (assignment_purpose IN ('REGULAR','PRACTICE')),
  response_type VARCHAR(20) NOT NULL CHECK (response_type IN ('ESSAY','OBJECTIVE')),
  instructions TEXT NOT NULL,
  scope_text TEXT,
  task_checklist JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(task_checklist) = 'array'),
  maximum_score NUMERIC(10,2) NOT NULL CHECK (maximum_score > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','CANCELLED')),
  available_from TIMESTAMPTZ,
  due_at TIMESTAMPTZ,
  time_limit_minutes INTEGER CHECK (time_limit_minutes > 0),
  attempt_limit INTEGER,
  published_at TIMESTAMPTZ,
  cancelled_at TIMESTAMPTZ,
  CHECK (assignment_purpose <> 'PRACTICE' OR response_type = 'OBJECTIVE'),
  CHECK ((assignment_purpose = 'PRACTICE' AND attempt_limit > 0) OR (assignment_purpose = 'REGULAR' AND attempt_limit IS NULL)),
  CHECK (available_from IS NULL OR due_at IS NULL OR due_at > available_from),
  CHECK (status <> 'PUBLISHED' OR (available_from IS NOT NULL AND due_at IS NOT NULL)),
  CHECK (status <> 'PUBLISHED' OR due_at > published_at),
  CHECK (status <> 'PUBLISHED' OR published_at IS NOT NULL),
  CHECK (status <> 'CANCELLED' OR cancelled_at IS NOT NULL)
);

CREATE TABLE questions (
  question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id BIGINT NOT NULL REFERENCES assignments(assignment_id),
  question_order INTEGER NOT NULL CHECK (question_order > 0),
  question_text TEXT NOT NULL CHECK (btrim(question_text) <> ''),
  maximum_points NUMERIC(10,2) NOT NULL CHECK (maximum_points > 0),
  options JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(options) = 'array'),
  UNIQUE (assignment_id, question_order)
);

CREATE TABLE submissions (
  submission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id BIGINT NOT NULL REFERENCES assignments(assignment_id),
  enrollment_id BIGINT NOT NULL REFERENCES class_enrollments(enrollment_id),
  attempt_number INTEGER NOT NULL CHECK (attempt_number > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS' CHECK (status IN ('IN_PROGRESS','SUBMITTED','GRADED','RELEASED','EXPIRED','VOID')),
  started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deadline_at TIMESTAMPTZ NOT NULL,
  submitted_at TIMESTAMPTZ,
  content TEXT,
  submission_link VARCHAR(2048),
  answer JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(answer) = 'array'),
  score NUMERIC(10,2) CHECK (score >= 0),
  feedback TEXT,
  graded_by BIGINT REFERENCES users(user_id),
  graded_at TIMESTAMPTZ,
  released_at TIMESTAMPTZ,
  UNIQUE (enrollment_id, assignment_id, attempt_number),
  CHECK (deadline_at > started_at),
  CHECK (submitted_at IS NULL OR submitted_at BETWEEN started_at AND deadline_at),
  CHECK (graded_at IS NULL OR submitted_at IS NOT NULL AND graded_at >= submitted_at),
  CHECK (released_at IS NULL OR graded_at IS NOT NULL AND released_at >= graded_at),
  CHECK (status IN ('SUBMITTED','GRADED','RELEASED') OR submitted_at IS NULL),
  CHECK (status NOT IN ('SUBMITTED','GRADED','RELEASED') OR submitted_at IS NOT NULL),
  CHECK (status NOT IN ('GRADED','RELEASED') OR (score IS NOT NULL AND graded_at IS NOT NULL)),
  CHECK (status <> 'GRADED' OR released_at IS NULL),
  CHECK ((status = 'RELEASED' AND released_at IS NOT NULL) OR (status <> 'RELEASED' AND released_at IS NULL)),
  CHECK (status NOT IN ('EXPIRED','VOID') OR (score IS NULL AND feedback IS NULL AND graded_by IS NULL AND graded_at IS NULL))
);
CREATE UNIQUE INDEX uq_submissions_one_in_progress ON submissions (enrollment_id, assignment_id) WHERE status = 'IN_PROGRESS';

