DROP TRIGGER IF EXISTS ams_teacher_history ON subject_classes;
CREATE TRIGGER ams_teacher_history AFTER INSERT OR UPDATE ON subject_classes FOR EACH ROW EXECUTE FUNCTION ams_record_responsibility();
