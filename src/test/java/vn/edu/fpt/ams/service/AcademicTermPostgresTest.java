package vn.edu.fpt.ams.service;

import static org.junit.jupiter.api.Assertions.*;
import java.sql.*;
import java.time.Instant;
import java.util.*;
import java.util.concurrent.*;
import org.junit.jupiter.api.*;
import vn.edu.fpt.ams.model.AcademicTerm;
import vn.edu.fpt.ams.util.*;

/** Uses an isolated random schema; no application table can be resolved through search_path. */
class AcademicTermPostgresTest {
  private String schema;
  private Connection admin;
  private Jdbc.Connections source;

  @BeforeEach void setup() throws Exception {
    Assumptions.assumeTrue(Boolean.getBoolean("assignment.db.tests"));
    schema="ams_term_test_"+UUID.randomUUID().toString().replace("-","");
    admin=DBConnection.getConnection();
    try(var s=admin.createStatement()) {s.execute("CREATE SCHEMA "+schema);}
    source=()->{
      Connection c=DBConnection.getConnection();
      try(var s=c.createStatement()){s.execute("SET search_path TO "+schema);}
      catch(SQLException ex){c.close();throw ex;}
      return c;
    };
    try(var c=source.open();var s=c.createStatement()) {
      s.execute("CREATE TABLE users(user_id BIGINT PRIMARY KEY,full_name TEXT,email TEXT,role TEXT,account_status TEXT,google_subject TEXT,password_hash TEXT,created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,last_login_at TIMESTAMPTZ,updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP)");
      s.execute("INSERT INTO users(user_id,full_name,email,role,account_status) VALUES(1,'Admin 1','a1@test.invalid','ADMIN','ACTIVE'),(2,'Admin 2','a2@test.invalid','ADMIN','ACTIVE')");
      s.execute("CREATE TABLE academic_terms(term_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,term_code TEXT UNIQUE,term_name TEXT,starts_at TIMESTAMPTZ,ends_at TIMESTAMPTZ,is_current BOOLEAN NOT NULL DEFAULT FALSE,is_active BOOLEAN NOT NULL DEFAULT TRUE,CHECK(NOT is_current OR is_active))");
      s.execute("CREATE UNIQUE INDEX one_legacy_current ON academic_terms(is_current) WHERE is_current");
      s.execute("CREATE TABLE subject_terms(term_id BIGINT REFERENCES academic_terms)");
    }
  }
  @AfterEach void close() throws Exception {
    if(admin!=null)try(var connection=admin;var s=connection.createStatement()){s.execute("DROP SCHEMA IF EXISTS "+schema+" CASCADE");}
  }

  @Test void simultaneousDifferentAdminsCannotCreateOverlappingEnabledTerms() throws Exception {
    var service=new MasterDataService(source);
    Instant start=Instant.now().plusSeconds(86400),end=start.plusSeconds(86400);
    var ready=new CountDownLatch(2);var go=new CountDownLatch(1);
    var pool=Executors.newFixedThreadPool(2);
    try {
      var futures=new ArrayList<Future<Boolean>>();
      for(long actor:List.of(1L,2L)) futures.add(pool.submit(()->{
        ready.countDown();if(!go.await(5,TimeUnit.SECONDS))throw new AssertionError("Start barrier timed out");
        try {service.createTerm(actor,new AcademicTerm(0,"TERM"+actor,"Term",start,end,false,true));return true;}
        catch(IllegalArgumentException expected){assertTrue(expected.getMessage().contains("trùng"));return false;}
      }));
      assertTrue(ready.await(5,TimeUnit.SECONDS));go.countDown();
      int saved=0;for(var f:futures)if(f.get(10,TimeUnit.SECONDS))saved++;
      assertEquals(1,saved);
      assertEquals(1,service.listTerms(1,null,true).size());
    } finally {go.countDown();pool.shutdownNow();}
  }

  @Test void currentLabelAndDaoIgnoreStalePersistedCurrentFlag() throws Exception {
    try(var c=source.open()) {
      Jdbc.update(c,"INSERT INTO academic_terms(term_code,term_name,starts_at,ends_at,is_current) VALUES('PAST','Past',statement_timestamp()-INTERVAL '2 days',statement_timestamp()-INTERVAL '1 day',TRUE),('NOW','Current',statement_timestamp()-INTERVAL '1 hour',statement_timestamp()+INTERVAL '1 day',FALSE)");
      assertEquals("NOW",new vn.edu.fpt.ams.dao.MasterDataDAO().findCurrentTerm(c).orElseThrow().termCode());
      assertTrue(vn.edu.fpt.ams.dao.DashboardDAO.findCurrentTermLabel(c).startsWith("NOW"));
    }
    assertFalse(new MasterDataService(source).listTerms(1,"PAST",null).get(0).current());
  }
}
