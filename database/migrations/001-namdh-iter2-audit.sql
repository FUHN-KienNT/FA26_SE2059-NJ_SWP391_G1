-- Additive migration for an initialized AMS database; preserves all existing data.
CREATE TABLE IF NOT EXISTS account_audit_events (
  event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT NOT NULL REFERENCES users(user_id),
  user_id BIGINT NOT NULL REFERENCES users(user_id),
  event_type VARCHAR(50) NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_account_audit_user_time ON account_audit_events(user_id,occurred_at);
