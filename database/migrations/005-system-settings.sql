BEGIN;
CREATE TABLE IF NOT EXISTS system_settings (
  setting_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  setting_type VARCHAR(30) NOT NULL,
  setting_value VARCHAR(30) NOT NULL,
  display_name VARCHAR(100) NOT NULL CHECK (btrim(display_name) <> ''),
  priority INTEGER NOT NULL CHECK (priority > 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (setting_type, setting_value),
  CHECK ((setting_type = 'USER_ROLE' AND setting_value IN ('ADMIN','EXPERT','TEACHER','STUDENT'))
      OR (setting_type = 'ASSIGNMENT_TYPE' AND setting_value IN ('REGULAR','PRACTICE'))
      OR (setting_type = 'RESPONSE_TYPE' AND setting_value IN ('ESSAY','OBJECTIVE')))
);
