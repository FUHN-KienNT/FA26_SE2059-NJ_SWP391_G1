CREATE TABLE IF NOT EXISTS project_groups (
    group_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL REFERENCES subject_classes(class_id),
    group_name VARCHAR(100) NOT NULL CHECK (length(btrim(group_name)) > 0),
    description VARCHAR(2000) NOT NULL DEFAULT '',
    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    leader_student_id BIGINT REFERENCES users(user_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (group_id, class_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_project_group_name ON project_groups(class_id, lower(btrim(group_name)));

CREATE TABLE IF NOT EXISTS project_group_members (
    member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL REFERENCES users(user_id),
    enrollment_id BIGINT NOT NULL REFERENCES class_enrollments(enrollment_id),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at TIMESTAMPTZ,
    FOREIGN KEY (group_id, class_id) REFERENCES project_groups(group_id, class_id),
    CHECK (left_at IS NULL OR left_at >= joined_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_student_active_class_group
    ON project_group_members(class_id, student_id) WHERE left_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_group_members ON project_group_members(group_id);
